def run_storage_failures(browser,path):
    context=browser.new_context(accept_downloads=True)
    page=context.new_page();page.goto(BASE+path);page.wait_for_selector('#english-question')
    page.locator('#daily-tab').click();page.locator('#add-phrase').click()
    page.get_by_label('English phrase/question',exact=True).fill('A session-safe phrase')
    page.get_by_role('button',name='Save phrase',exact=True).click();expect(page.locator('#dialog')).not_to_be_visible()
    check(page.locator('#card-count').inner_text()=='0','blank flashcard section creates none')
    with page.expect_download() as got:page.locator('#export').click()
    backup=ROOT/'.test-results'/'safety.json';got.value.save_as(backup)
    before=page.evaluate('(k)=>localStorage.getItem(k)',KEY)
    page.locator('#progress-file').set_input_files(str(backup))
    page.evaluate("()=>{Storage.prototype.setItem=function(){throw new DOMException('quota','QuotaExceededError')}}")
    page.get_by_role('button',name='Confirm restore',exact=True).click()
    expect(page.locator('#dialog-body')).to_contain_text('Current data has been preserved')
    check(page.evaluate('(k)=>localStorage.getItem(k)',KEY)==before,'failed browser durable restore atomic')
    page.get_by_role('button',name='Cancel',exact=True).click()
    page.locator('#practice-tab').click();expect(page.locator('#storage-status')).to_be_visible()
    check('Session only' in page.locator('#storage-status').inner_text(),'regular quota failure is visible session-only')
    with page.expect_download() as got:page.locator('#export').click()
    got.value.save_as(backup)
    check(json.loads(backup.read_text())['user']['prefs']['section']=='practice','session-only data exports current state')
    context.close()
    denied=browser.new_context(accept_downloads=True)
    denied.add_init_script("Storage.prototype.getItem=function(){throw new DOMException('denied','SecurityError')};Storage.prototype.setItem=function(){throw new DOMException('denied','SecurityError')}")
    page=denied.new_page();page.goto(BASE+path);page.wait_for_selector('#english-question')
    check(page.locator('#storage-status').is_visible(),'initial denied storage clearly reported')
    page.locator('#daily-tab').click();page.locator('#add-phrase').click();page.get_by_label('English phrase/question',exact=True).fill('Memory only')
    page.get_by_role('button',name='Save phrase',exact=True).click();expect(page.locator('#dialog')).not_to_be_visible()
    with page.expect_download() as got:page.locator('#export').click()
    got.value.save_as(backup)
    check(json.loads(backup.read_text())['user']['phrases'][0]['english']=='Memory only','initial denied storage allows work and real export')
    denied.close()

